// Bons mois pour prospecter : activité pas au pic, et un pic dans les deux mois qui suivent
// : le commerçant prépare sa saison et a encore le temps d'écouter.
export function bestMonths(saison) {
  return saison.map((lv, m) => lv < 2 && (saison[(m + 1) % 12] === 2 || saison[(m + 2) % 12] === 2));
}
